-- StockLine - Initial schema
-- PostgreSQL 17 / Flyway V1

CREATE TABLE location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    type VARCHAR(20) NOT NULL,
    address VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_location_type
        CHECK (type IN ('WAREHOUSE', 'STORE'))
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    location_id BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_app_user_location
        FOREIGN KEY (location_id) REFERENCES location(id),
    CONSTRAINT chk_app_user_role
        CHECK (role IN ('ADMIN', 'MANAGER', 'SELLER')),
    CONSTRAINT chk_app_user_location
        CHECK (role = 'ADMIN' OR location_id IS NOT NULL)
);

CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    category VARCHAR(100),
    unit_price_minor BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    reorder_threshold BIGINT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_product_unit_price
        CHECK (unit_price_minor >= 0),
    CONSTRAINT chk_product_reorder_threshold
        CHECK (reorder_threshold >= 0)
);

CREATE TABLE supplier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    contact VARCHAR(500)
);

CREATE TABLE stock_level (
    product_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_stock_level
        PRIMARY KEY (product_id, location_id),
    CONSTRAINT fk_stock_level_product
        FOREIGN KEY (product_id) REFERENCES product(id),
    CONSTRAINT fk_stock_level_location
        FOREIGN KEY (location_id) REFERENCES location(id),
    CONSTRAINT chk_stock_level_quantity
        CHECK (quantity >= 0),
    CONSTRAINT chk_stock_level_version
        CHECK (version >= 0)
);

CREATE TABLE stock_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    type VARCHAR(30) NOT NULL,
    quantity_delta BIGINT NOT NULL,
    reference_type VARCHAR(50),
    reference_id BIGINT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_id BIGINT,
    note TEXT,
    CONSTRAINT fk_stock_movement_product
        FOREIGN KEY (product_id) REFERENCES product(id),
    CONSTRAINT fk_stock_movement_location
        FOREIGN KEY (location_id) REFERENCES location(id),
    CONSTRAINT fk_stock_movement_actor
        FOREIGN KEY (actor_id) REFERENCES app_user(id),
    CONSTRAINT chk_stock_movement_type
        CHECK (type IN (
            'PURCHASE_RECEIPT',
            'SALE',
            'TRANSFER_OUT',
            'TRANSFER_IN',
            'LOSS',
            'ADJUSTMENT',
            'RETURN'
        )),
    CONSTRAINT chk_stock_movement_quantity_delta
        CHECK (quantity_delta <> 0)
);

CREATE TABLE sale (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL,
    seller_id BIGINT NOT NULL,
    total_minor BIGINT NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sale_location
        FOREIGN KEY (location_id) REFERENCES location(id),
    CONSTRAINT fk_sale_seller
        FOREIGN KEY (seller_id) REFERENCES app_user(id),
    CONSTRAINT chk_sale_total_minor
        CHECK (total_minor >= 0)
);

CREATE TABLE sale_line (
    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL,
    unit_price_minor BIGINT NOT NULL,
    CONSTRAINT pk_sale_line
        PRIMARY KEY (sale_id, product_id),
    CONSTRAINT fk_sale_line_sale
        FOREIGN KEY (sale_id) REFERENCES sale(id),
    CONSTRAINT fk_sale_line_product
        FOREIGN KEY (product_id) REFERENCES product(id),
    CONSTRAINT chk_sale_line_quantity
        CHECK (quantity > 0),
    CONSTRAINT chk_sale_line_unit_price
        CHECK (unit_price_minor >= 0)
);

CREATE TABLE transfer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_location_id BIGINT NOT NULL,
    to_location_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
    requested_by BIGINT NOT NULL,
    approved_by BIGINT,
    shipped_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_transfer_from_location
        FOREIGN KEY (from_location_id) REFERENCES location(id),
    CONSTRAINT fk_transfer_to_location
        FOREIGN KEY (to_location_id) REFERENCES location(id),
    CONSTRAINT fk_transfer_requested_by
        FOREIGN KEY (requested_by) REFERENCES app_user(id),
    CONSTRAINT fk_transfer_approved_by
        FOREIGN KEY (approved_by) REFERENCES app_user(id),
    CONSTRAINT chk_transfer_distinct_locations
        CHECK (from_location_id <> to_location_id),
    CONSTRAINT chk_transfer_status
        CHECK (status IN (
            'REQUESTED',
            'APPROVED',
            'SHIPPED',
            'RECEIVED',
            'REJECTED',
            'CANCELLED'
        ))
);

CREATE TABLE transfer_line (
    transfer_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity_requested BIGINT NOT NULL,
    quantity_shipped BIGINT NOT NULL DEFAULT 0,
    quantity_received BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_transfer_line
        PRIMARY KEY (transfer_id, product_id),
    CONSTRAINT fk_transfer_line_transfer
        FOREIGN KEY (transfer_id) REFERENCES transfer(id),
    CONSTRAINT fk_transfer_line_product
        FOREIGN KEY (product_id) REFERENCES product(id),
    CONSTRAINT chk_transfer_line_requested
        CHECK (quantity_requested > 0),
    CONSTRAINT chk_transfer_line_shipped
        CHECK (
            quantity_shipped >= 0
            AND quantity_shipped <= quantity_requested
        ),
    CONSTRAINT chk_transfer_line_received
        CHECK (
            quantity_received >= 0
            AND quantity_received <= quantity_shipped
        )
);

CREATE TABLE purchase_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    ordered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_purchase_order_supplier
        FOREIGN KEY (supplier_id) REFERENCES supplier(id),
    CONSTRAINT fk_purchase_order_location
        FOREIGN KEY (location_id) REFERENCES location(id),
    CONSTRAINT chk_purchase_order_status
        CHECK (status IN (
            'DRAFT',
            'SENT',
            'PARTIALLY_RECEIVED',
            'RECEIVED',
            'CANCELLED'
        ))
);

CREATE TABLE purchase_order_line (
    purchase_order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity_ordered BIGINT NOT NULL,
    quantity_received BIGINT NOT NULL DEFAULT 0,
    unit_cost_minor BIGINT NOT NULL,
    CONSTRAINT pk_purchase_order_line
        PRIMARY KEY (purchase_order_id, product_id),
    CONSTRAINT fk_purchase_order_line_order
        FOREIGN KEY (purchase_order_id) REFERENCES purchase_order(id),
    CONSTRAINT fk_purchase_order_line_product
        FOREIGN KEY (product_id) REFERENCES product(id),
    CONSTRAINT chk_purchase_order_line_ordered
        CHECK (quantity_ordered > 0),
    CONSTRAINT chk_purchase_order_line_received
        CHECK (
            quantity_received >= 0
            AND quantity_received <= quantity_ordered
        ),
    CONSTRAINT chk_purchase_order_line_cost
        CHECK (unit_cost_minor >= 0)
);

CREATE TABLE stock_snapshot_daily (
    snapshot_date DATE NOT NULL,
    product_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL,
    CONSTRAINT pk_stock_snapshot_daily
        PRIMARY KEY (snapshot_date, product_id, location_id),
    CONSTRAINT fk_stock_snapshot_product
        FOREIGN KEY (product_id) REFERENCES product(id),
    CONSTRAINT fk_stock_snapshot_location
        FOREIGN KEY (location_id) REFERENCES location(id),
    CONSTRAINT chk_stock_snapshot_quantity
        CHECK (quantity >= 0)
);

CREATE TABLE weekly_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    location_id BIGINT,
    payload JSONB NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_weekly_report_location
        FOREIGN KEY (location_id) REFERENCES location(id),
    CONSTRAINT chk_weekly_report_period
        CHECK (period_end >= period_start),
    CONSTRAINT uq_weekly_report_period_location
        UNIQUE NULLS NOT DISTINCT (period_start, location_id)
);

-- Stock movements are append-only: corrections must be recorded
-- as new inverse movements, never by editing or deleting history.
CREATE FUNCTION prevent_stock_movement_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'stock_movement rows are immutable';
END;
$$;

CREATE TRIGGER trg_stock_movement_immutable
BEFORE UPDATE OR DELETE ON stock_movement
FOR EACH ROW
EXECUTE FUNCTION prevent_stock_movement_mutation();